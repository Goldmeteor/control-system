export function allCybersecurityTaskIds(): string[] {
  return cybersecurityWeeks.flatMap((week) =>
    week.groups.flatMap((group, groupIndex) =>
      group.tasks.map((_, taskIndex) => `sec${week.id}-g${groupIndex}-t${taskIndex}`),
    ),
  )
}
